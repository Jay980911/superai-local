def _clamp(v, lo=0.0, hi=1.0):
    return max(lo, min(hi, v))


def hsl_to_hex(h, s, l):
    """h:0-360, s:0-100, l:0-100 -> #RRGGBB。确定性、无第三方依赖。"""
    h = float(h) % 360.0
    s = _clamp(float(s) / 100.0)
    l = _clamp(float(l) / 100.0)
    c = (1 - abs(2 * l - 1)) * s
    x = c * (1 - abs((h / 60.0) % 2 - 1))
    m = l - c / 2.0
    if h < 60:
        r, g, b = c, x, 0
    elif h < 120:
        r, g, b = x, c, 0
    elif h < 180:
        r, g, b = 0, c, x
    elif h < 240:
        r, g, b = 0, x, c
    elif h < 300:
        r, g, b = x, 0, c
    else:
        r, g, b = c, 0, x
    R = int(round((r + m) * 255))
    G = int(round((g + m) * 255))
    B = int(round((b + m) * 255))
    return "#{:02X}{:02X}{:02X}".format(R, G, B)


def hex_to_rgb(hx):
    hx = hx.lstrip("#")
    if len(hx) == 3:
        hx = "".join(c * 2 for c in hx)
    return tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4))


def _lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def contrast_ratio(hx1, hx2):
    """WCAG 对比度，1.0-21.0。"""
    r1, g1, b1 = hex_to_rgb(hx1)
    r2, g2, b2 = hex_to_rgb(hx2)
    l1 = 0.2126 * _lin(r1) + 0.7152 * _lin(g1) + 0.0722 * _lin(b1)
    l2 = 0.2126 * _lin(r2) + 0.7152 * _lin(g2) + 0.0722 * _lin(b2)
    lighter, darker = max(l1, l2), min(l1, l2)
    return round((lighter + 0.05) / (darker + 0.05), 2)


def text_on(bg_hex, dark="#16181D", light="#F7F8FA"):
    """返回与背景对比度更高的文字色（WCAG AA 友好）。"""
    return dark if contrast_ratio(bg_hex, dark) >= contrast_ratio(bg_hex, light) else light


def _scheme_hues(base, scheme):
    """返回一组与 base 色相配合的色相列表。"""
    if scheme == "monochromatic":
        return [base]
    if scheme == "analogous":
        return [base, (base + 30) % 360, (base - 30) % 360]
    if scheme == "complementary":
        return [base, (base + 180) % 360]
    if scheme == "triadic":
        return [base, (base + 120) % 360, (base + 240) % 360]
    if scheme == "split":
        return [base, (base + 150) % 360, (base + 210) % 360]
    return [base]


SCHEMES = ["analogous", "complementary", "triadic", "monochromatic", "split-complementary"]
MOODS = ["Calm", "Vivid", "Premium", "Playful", "Corporate", "Organic",
         "Cyber", "Warm", "Cool", "Muted", "Energetic", "Editorial"]


def build_palettes(n=161):
    """确定性生成 n 个调色板，每个含 light/dark 两套角色色（真实可复现 hex）。

    角色：primary / secondary / accent(CTA) / bg / surface / text / border
    """
    out = []
    for i in range(n):
        hue = (i * 137.508) % 360.0          # 黄金角分布，色相均匀不聚类
        scheme = SCHEMES[i % len(SCHEMES)]
        mood = MOODS[i % len(MOODS)]
        hues = _scheme_hues(hue, scheme)
        name = "{} {} {:03d}".format(mood, scheme.replace("-", " ").title(), i + 1)

        # 情绪 -> 饱和度/明度偏好
        sat = {"Vivid": 72, "Cyber": 80, "Energetic": 78, "Playful": 70,
               "Premium": 38, "Muted": 28, "Calm": 42, "Corporate": 50,
               "Organic": 45, "Warm": 60, "Cool": 48, "Editorial": 35}.get(mood, 55)
        light = {"Premium": 42, "Calm": 46, "Muted": 50, "Editorial": 40}.get(mood, 48)

        primary = hsl_to_hex(hues[0], sat, light)
        secondary = hsl_to_hex(hues[1 % len(hues)], sat, min(light + 8, 70))
        # CTA 取最高对比的鲜明色
        accent = hsl_to_hex(hues[0], min(sat + 18, 90), 50)

        bg = hsl_to_hex(hues[0], 18, 97)
        surface = hsl_to_hex(hues[0], 22, 100)
        border = hsl_to_hex(hues[0], 30, 88)
        text = text_on(bg)
        muted = text_on(bg)
        # dark 变体
        bg_d = hsl_to_hex(hues[0], 22, 9)
        surface_d = hsl_to_hex(hues[0], 24, 14)
        border_d = hsl_to_hex(hues[0], 28, 24)
        text_d = text_on(bg_d, dark="#0B0C10", light="#EDEFF3")

        out.append({
            "id": i + 1,
            "name": name,
            "scheme": scheme,
            "mood": mood,
            "base_hue": round(hue, 1),
            "light": {
                "primary": primary, "secondary": secondary, "accent": accent,
                "bg": bg, "surface": surface, "border": border,
                "text": text, "muted": muted,
            },
            "dark": {
                "primary": hsl_to_hex(hues[0], sat, 62),
                "secondary": hsl_to_hex(hues[1 % len(hues)], sat, 66),
                "accent": accent,
                "bg": bg_d, "surface": surface_d, "border": border_d,
                "text": text_d, "muted": text_d,
            },
        })
    return out


